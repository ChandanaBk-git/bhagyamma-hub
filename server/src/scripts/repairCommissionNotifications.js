require("dotenv").config();

const mongoose = require("mongoose");

const connectDB = require("../config/database");

const Notification = require("../models/Notification");
const CommissionTransaction = require("../models/commissionTransaction.model");
const User = require("../models/user.model");
const Order = require("../models/order.model");
const OrderItem = require("../models/orderItem.model");

const money = (amount) =>
  `₹${Number(amount || 0).toLocaleString("en-IN")}`;

const repairCommissionNotification = async (notification) => {
  const transaction = await CommissionTransaction.findById(
    notification.referenceId
  ).lean();

  if (!transaction) {
    console.log(
      `Skipped: Commission transaction not found: ${notification.referenceId}`
    );
    return false;
  }

  const [receiver, sourceUser, order] = await Promise.all([
    User.findById(transaction.receiver)
      .select("name userId")
      .lean(),

    User.findById(transaction.fromUser)
      .select("name userId")
      .lean(),

    transaction.order
      ? Order.findById(transaction.order)
          .select("orderNumber")
          .lean()
      : Promise.resolve(null),
  ]);

  if (!receiver || !sourceUser) {
    console.log(
      `Skipped: Missing receiver/source user for ${transaction._id}`
    );
    return false;
  }

  const receiverName = receiver.name || "Member";
  const sourceName = sourceUser.name || "A member";
  const amount = money(transaction.commissionAmount);
  const level = Number(transaction.level || 1);

  let message = "";

  if (transaction.type === "JOINING") {
    const joiningAmount = money(transaction.joiningAmount);

    message =
      `${receiverName}, you received ${amount} commission ` +
      `from ${sourceName}'s membership activation of ${joiningAmount}. ` +
      `Level ${level} joining commission.`;
  } else if (transaction.type === "ORDER") {
    const orderNumber = order?.orderNumber || "an order";

    const items = transaction.order
      ? await OrderItem.find({
          orderId: transaction.order,
        })
          .select("productName quantity")
          .lean()
      : [];

    const productNames = items.length
      ? items
          .map((item) =>
            item.quantity > 1
              ? `${item.productName} × ${item.quantity}`
              : item.productName
          )
          .join(", ")
      : "product purchase";

    message =
      `${receiverName}, you received ${amount} commission ` +
      `from ${sourceName}'s purchase of ${productNames}. ` +
      `Order ${orderNumber} • Level ${level} product-order commission.`;
  } else {
    message =
      `${receiverName}, you received ${amount} commission ` +
      `generated by ${sourceName}. ` +
      `Level ${level} • ${transaction.type || "Commission"}.`;
  }

  await Notification.updateOne(
    {
      _id: notification._id,
      referenceId: transaction._id,
    },
    {
      $set: {
        title: "Commission Received",
        message,
        metadata: {
          ...(notification.metadata || {}),
          amount: transaction.commissionAmount,
          level,
          commissionType: transaction.type,
          sourceMemberName: sourceName,
          sourceMemberId: sourceUser.userId || null,
          joiningAmount: transaction.joiningAmount || 0,
          orderId: transaction.order || null,
          orderNumber: order?.orderNumber || null,
        },
      },
    }
  );

  console.log(`Updated notification: ${notification._id}`);

  return true;
};

const main = async () => {
  try {
    await connectDB();

    console.log("MongoDB connected. Starting notification repair...");

    const notifications = await Notification.find({
      type: "COMMISSION_RECEIVED",
      referenceType: "CommissionTransaction",
    })
      .sort({ createdAt: 1 })
      .lean();

    console.log(`Found ${notifications.length} commission notifications.`);

    let updated = 0;
    let skipped = 0;

    for (const notification of notifications) {
      try {
        const result = await repairCommissionNotification(notification);

        if (result) {
          updated++;
        } else {
          skipped++;
        }
      } catch (error) {
        skipped++;
        console.error(
          `Failed notification ${notification._id}:`,
          error.message
        );
      }
    }

    console.log("--------------------------------");
    console.log("Commission notification repair completed.");
    console.log(`Updated: ${updated}`);
    console.log(`Skipped: ${skipped}`);
    console.log("--------------------------------");
  } catch (error) {
    console.error("Repair failed:", error);
    process.exitCode = 1;
  } finally {
    await mongoose.disconnect();
  }
};

main();